const crearOrden = ({ minutos, ...datos }) => {
  const fecha = new Date(Date.now() - minutos * 60 * 1000);

  return {
    ...datos,
    created_at: fecha.toISOString(),
    hora: fecha.toLocaleTimeString('es-SV', {
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
    }),
  };
};

